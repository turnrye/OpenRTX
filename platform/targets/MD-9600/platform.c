/**
 * Drive a gpio as an output.
 */
static void setOutput(GPIO_TypeDef *port, uint8_t pin, bool high)
{
    gpio_setMode(port, pin, OUTPUT);

    if(high)
        gpio_setPin(port, pin);
    else
        gpio_clearPin(port, pin);
}

/**
 * Power both receivers, transmitters off. The AK2365A IF chips of the V1-V4
 * boards run from the receiver supplies. The supplies take the SWD pins: from
 * here on, a debugger connects under reset only.
 */
static void receiversOn(bool on)
{
    setOutput(RF_APC_EN, false);
    setOutput(RF_T5_UHF, false);
    setOutput(RF_T5_VHF, false);
    setOutput(VCO_SEL_UHF, on);
    setOutput(VCO_SEL_VHF, on);
    setOutput(RF_C5_UHF, on);
    setOutput(RF_C5_VHF, on);
    setOutput(RF_R5_UHF, on);
    setOutput(RF_R5_VHF, on);
}

/**
 * Tell the board revisions apart: the V1-V4 boards have an AK2365A IF chip
 * per band, the V4A/V5 boards none, and no other readable part differs.
 * Sequence from RadioFoundry, boards/md9600/rfseq_md9600.c
 * md9600_rf_if_detect() and docs/spec/hardware-md9600.md sections 5.4 and 16,
 * https://github.com/radiofoundry/radiofoundry
 *
 * @return MD9600_FLAGS_V5 when neither chip drives its data line,
 * MD9600_FLAGS_V1_V4 when either answers, 0 when unsure.
 */
static uint16_t detectRevision()
{
    receiversOn(true);
    delayMs(3);

    spiBitbang_init(&if_spi);
    int vhf = AK2365A_probe(&ifVhf);
    int uhf = AK2365A_probe(&ifUhf);
    spiBitbang_terminate(&if_spi);

    receiversOn(false);

    if((vhf == 0) || (uhf == 0))
        return MD9600_FLAGS_V1_V4;

    if((vhf == -ENODEV) && (uhf == -ENODEV))
        return MD9600_FLAGS_V5;

    return 0;
}

void platform_init()
{
    /* Enable 8V power supply rail */
    gpio_setMode(PWR_SW, OUTPUT);
    gpio_setPin(PWR_SW);

    gpio_setMode(PTT_SW, INPUT);

    gpio_setMode(AIN_VBAT,      ANALOG);
    gpio_setMode(AIN_MIC,       ANALOG);
    gpio_setMode(AIN_RSSI_VHF,  ANALOG);
    gpio_setMode(AIN_RSSI_UHF,  ANALOG);
    gpio_setMode(AIN_SW2,       ANALOG);
    gpio_setMode(AIN_SW1,       ANALOG);
    gpio_setMode(AIN_NOISE_UHF, ANALOG);
    gpio_setMode(AIN_NOISE_VHF, ANALOG);

    /* Initialise ADC1, for vbat, RSSI, ... */
    adcStm32_init(&adc1);

    /*
     * Initialise SPI2 for external flash and LCD
     */
    gpio_setMode(SPI2_CLK, ALTERNATE | ALTERNATE_FUNC(5));
    gpio_setMode(SPI2_SDO, ALTERNATE | ALTERNATE_FUNC(5));
    gpio_setMode(SPI2_SDI, ALTERNATE | ALTERNATE_FUNC(5));
    spiStm32_init(&spi2, 1300000, 0);

    memset(&hwInfo, 0x00, sizeof(hwInfo));

    nvm_init();                      /* Initialise non volatile memory manager */
    nvm_readHwInfo(&hwInfo);         /* Load hardware information data         */
    hwInfo.flags = detectRevision(); /* Board revision                         */
    toneGen_init();                  /* Initialise tone generator              */

    /*
     * PC7 drives the reference oscillator's modulation input: driven low it
     * pulls the reference. Tones are generated by the HR_C6000, so leave it
     * released, as at power-up. RadioFoundry, docs/spec/hardware-md9600.md,
     * pin table and section 19.9.
     */
    gpio_setMode(CTCSS_OUT, INPUT);
    rtc_init();                      /* Initialise RTC                         */
    backlight_init();                /* Initialize Backlight                   */
    chSelector_init();               /* Initialise channel selector handler    */
    audio_init();                    /* Initialise audio management module     */
}

void platform_terminate()
{
    /* Shut down all the modules */
    adcStm32_terminate(&adc1);
    gpsStm32_terminate();
    toneGen_terminate();
    chSelector_terminate();
    audio_terminate();

    /* Finally, remove power supply */
    gpio_clearPin(PWR_SW);

    /*
     * MD-9600 does not have a proper power on/off mechanism and the MCU is
     * always powered. Thus, for turn off, perform a system reset.
     */
    NVIC_SystemReset();
    while(1) ;
}

void platform_enterBootloader()
{
    /*
     * The TYT bootloader has no software entry: it stays in DFU only when the
     * keys are held at power on or when the application's initial stack
     * pointer fails (SP & 0x2FFE0000) == 0x20000000. Clear the stack pointer's
     * top byte at 0x0800C003 (programming only clears bits, no erase needed)
     * and reset. The next firmware write restores it. The bootloader in
     * sectors 0-2 is never touched.
     *
     * Approach from RadioFoundry, docs/spec/hardware-dm1701.md section 15.4.
     */
    volatile uint8_t *spTop = (volatile uint8_t *) 0x0800C003;

    gpio_clearPin(PWR_SW);
    __disable_irq();

    if(FLASH->CR & FLASH_CR_LOCK)
    {
        FLASH->KEYR = 0x45670123;
        FLASH->KEYR = 0xCDEF89AB;
    }

    while(FLASH->SR & FLASH_SR_BSY) ;
    FLASH->SR = FLASH_SR_PGSERR | FLASH_SR_PGPERR | FLASH_SR_PGAERR
              | FLASH_SR_WRPERR;
    FLASH->CR = FLASH_CR_PG;            /* Byte-wide programming */
    *spTop = 0x00;
    while(FLASH->SR & FLASH_SR_BSY) ;
    FLASH->CR = FLASH_CR_LOCK;

    NVIC_SystemReset();
    while(1) ;
}

uint16_t platform_getVbat()
{
    /*
     * Battery voltage is measured through an 1:5.7 voltage divider and
     * adc1_getMeasurement returns a value in uV.
     */
    uint32_t vbat = adc_getVoltage(&adc1, ADC_VBAT_CH) * 57;
    return vbat / 10000;
}

uint8_t platform_getMicLevel()
{
    /* Value from ADC is 12 bit wide: shift right by four to get 0 - 255 */
    return adc_getRawSample(&adc1, ADC_VOX_CH) >> 4;
}

uint8_t platform_getVolumeLevel()
{
    /*
     * The volume knob is analog only, after the audio switches, and no ADC
     * input reads it: RadioFoundry, docs/spec/hardware-md9600.md section 6.1.
     */
    return 0;
}

bool platform_getPttStatus()
{
    /* PTT line has a pullup resistor with PTT switch closing to ground */
    return (gpio_readPin(PTT_SW) == 0) ? true : false;
}

bool platform_pwrButtonStatus()
{
    /*
     * The power on/off button, when pressed, connects keyboard coloumn 3 to
     * row 3. Here we set coloumn to input with pull up mode and row to output
     * mode, consistently with keyboard driver.
     */

    gpio_setMode(KB_COL3, INPUT_PULL_UP);
    gpio_setMode(KB_ROW3, OUTPUT);

    /*
     * Critical section to avoid stomping the keyboard driver.
     * Also, working at register level to keep it as short as possible
     */
    __disable_irq();
    uint32_t prevRowState = GPIOD->ODR & (1 << 4);  /* Row 3 is PD4 */
    GPIOD->BSRR = 1 << (4 + 16);                    /* PD4 low      */
    delayUs(10);
    uint32_t btnStatus = GPIOE->IDR & 0x01;         /* Col 3 is PE0 */
    GPIOD->ODR |= prevRowState;                     /* Restore PD4  */
    __enable_irq();

    /*
     * Power button API requires this function to return true if power is
     * enabled. To comply to the requirement this function behaves in this way:
     * - if there is no new press, return current status of PWR_SW. A press
     *   still held from the previous call is not new, and pwrBtnPressed
     *   starts true so a press held through the reset that turns the radio
     *   off is not new either.
     * - if there is a new press and PWR_SW is low, return true as user wants
     *   to turn the radio on.
     * - if there is a new press and PWR_SW is high, return false as user
     *   wants to turn the radio off.
     *
     * Power button follows an active-low logic: btnStatus is low when button
     * is pressed
     */
    bool newPress = ((btnStatus == 0) && (pwrBtnPressed == false));

    pwrBtnPressed = (btnStatus == 0);

    if(newPress)
        return !gpio_readPin(PWR_SW);

    /* We get here if there is no new press, just return PWR_SW status */
    return gpio_readPin(PWR_SW);
}

